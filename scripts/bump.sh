#!/usr/bin/env bash
# Bump de version + commit + tag. Usage : ./scripts/bump.sh patch|minor|major
# Ensuite : git push github main && git push github vX.Y.Z  (déclenche la release)
set -euo pipefail
cd "$(dirname "$0")/.."
TYPE=${1:-}
[ -n "$TYPE" ] || { echo "usage: $0 patch|minor|major"; exit 1; }

V=$(node scripts/bump.js "$TYPE" | tail -1)
git add manifest.json CHANGELOG.md
git commit -m "v$V

Generated by Mistral Vibe.
Co-Authored-By: Mistral Vibe <vibe@mistral.ai>"
git tag "v$V"
echo "OK: commit + tag v$V créés."
echo "Publie avec : git push github main && git push github v$V"
